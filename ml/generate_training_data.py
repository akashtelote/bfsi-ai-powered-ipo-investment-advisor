def build_dataframe():
    cols = build_columns()
    all_rows = REAL_IPOS + EXTRA_REAL_IPOS
    df = pd.DataFrame(all_rows, columns=cols)

    # Generate synthetic IPOs to reach ~80 total
    n_existing = len(df)
    n_synthetic = max(0, 80 - n_existing)
    print(f"[INFO] Real IPOs: {n_existing}, Synthetic to generate: {n_synthetic}")

    if n_synthetic > 0:
        synthetic = _generate_synthetic(n_synthetic)
        df = pd.concat([df, synthetic], ignore_index=True)

    # Add ipo_id column
    df.insert(0, "ipo_id", df["company_name"].str.lower()
              .str.replace(r"[^a-z0-9]+", "_", regex=True)
              .str.strip("_")
              .str[:30]
              + "_" + pd.Series(range(len(df))).astype(str))

    return df


def _generate_synthetic(n: int) -> pd.DataFrame:
    """Generate n synthetic IPOs with realistic distributions across risk buckets."""
    rows = []
    sectors = ["IT Services", "BFSI", "Healthcare", "Manufacturing",
               "Consumer", "Infrastructure", "Renewable Energy", "Fintech", "Others"]
    sector_weights = [0.18, 0.15, 0.12, 0.15, 0.12, 0.08, 0.08, 0.08, 0.04]

    # Risk bucket sizes: Low 40%, Medium 35%, High 25%
    buckets = ["low"] * int(n * 0.40) + ["medium"] * int(n * 0.35) + ["high"] * (n - int(n * 0.40) - int(n * 0.35))
    rng.shuffle(buckets)

    for i, bucket in enumerate(buckets):
        sec = rng.choice(sectors, p=sector_weights)
        row = _synthetic_ipo(i + 100, sec, bucket)
        rows.append(row)

    return pd.DataFrame(rows, columns=build_columns())


def _synthetic_ipo(idx: int, sector: str, bucket: str) -> tuple:
    """Generate one synthetic IPO row for the given risk bucket."""

    def u(lo, hi): return float(rng.uniform(lo, hi))
    def n(mu, sig, lo=None, hi=None):
        v = float(rng.normal(mu, sig))
        if lo is not None: v = max(lo, v)
        if hi is not None: v = min(hi, v)
        return v

    if bucket == "low":
        listing_gain = n(55, 30, 21, 180)
        sub = n(60, 40, 15, 250)
        ebitda_m = n(26, 8, 14, 50)
        net_m = n(16, 6, 8, 35)
        roe = n(30, 8, 18, 55)
        roce = n(28, 8, 16, 50)
        rev_cagr = n(25, 10, 10, 55)
        pat_cagr = n(30, 12, 12, 70)
        de = n(0.25, 0.15, 0.0, 0.8)
        int_cov = n(14, 5, 6, 30)
        promoter = n(65, 10, 40, 82)
        ofs = n(30, 20, 0, 80)
        gmp_t3 = n(40, 25, 5, 120)
        sentiment = n(78, 8, 60, 95)
        news_vol = int(n(120, 60, 30, 400))
        brlm = n(8.8, 0.5, 7.5, 10.0)
    elif bucket == "medium":
        listing_gain = n(10, 8, 0, 20)
        sub = n(18, 12, 2, 60)
        ebitda_m = n(15, 6, 5, 30)
        net_m = n(8, 5, 0, 22)
        roe = n(16, 6, 5, 30)
        roce = n(14, 5, 4, 28)
        rev_cagr = n(16, 7, 5, 35)
        pat_cagr = n(14, 8, -5, 35)
        de = n(0.65, 0.30, 0.1, 1.8)
        int_cov = n(7, 3, 2, 16)
        promoter = n(52, 14, 30, 78)
        ofs = n(45, 20, 0, 90)
        gmp_t3 = n(12, 8, -5, 35)
        sentiment = n(62, 10, 40, 82)
        news_vol = int(n(70, 30, 20, 200))
        brlm = n(8.2, 0.6, 7.0, 9.5)
    else:  # high
        listing_gain = n(-15, 12, -50, -0.1)
        sub = n(3, 2, 0.5, 10)
        ebitda_m = n(3, 8, -20, 18)
        net_m = n(-15, 15, -55, 5)
        roe = n(-5, 12, -30, 15)
        roce = n(-3, 10, -25, 14)
        rev_cagr = n(10, 10, -10, 35)
        pat_cagr = n(-20, 20, -65, 15)
        de = n(1.5, 0.8, 0.2, 3.5)
        int_cov = n(2, 2, -3, 8)
        promoter = n(35, 15, 10, 65)
        ofs = n(65, 18, 20, 100)
        gmp_t3 = n(-5, 10, -20, 15)
        sentiment = n(48, 12, 25, 72)
        news_vol = int(n(50, 30, 10, 180))
        brlm = n(7.5, 0.8, 6.0, 9.0)

    fresh = max(0.0, 100.0 - ofs)
    qib_sub = sub * n(3.5, 0.5, 1.5, 6.0)
    hni_sub = sub * n(0.8, 0.2, 0.3, 1.5)
    rii_sub = sub * n(0.3, 0.1, 0.1, 0.8)
    allot = max(0.05, min(0.95, 1.0 / max(rii_sub, 0.5)))

    current_r = n(2.0, 0.5, 0.8, 5.0) if bucket == "low" else n(1.5, 0.4, 0.7, 3.5) if bucket == "medium" else n(1.2, 0.3, 0.5, 2.5)
    cash_r = current_r * n(0.42, 0.08, 0.2, 0.8)

    issue_cr = rng.choice([
        n(500, 200, 100, 1200), n(2000, 800, 800, 5000),
        n(8000, 3000, 3000, 20000)
    ], p=[0.5, 0.35, 0.15])
    pb_high = n(300, 150, 50, 2000)
