    nifty_ret = n(4.2, 4.0, -8, 14)
    vix = n(15.4, 3.0, 10, 26)
    anchor_pct = n(42, 8, 25, 60)
    co_age = n(18, 10, 3, 55)

    name = f"Synthetic IPO {idx} ({sector[:4]})"
